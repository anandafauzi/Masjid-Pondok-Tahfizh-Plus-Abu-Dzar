import { prisma } from "@/lib/prisma";
import { addDaysUTC, todayDateOnly } from "@/lib/datetime";
import { saveDisplayThemePatch } from "@/lib/settings";
import {
  DAYS_OF_WEEK,
  PRAYERS,
  WeeklyImamItem,
} from "@/types/weekly-imam";

export { DAYS_OF_WEEK, PRAYERS, type WeeklyImamItem };

/**
 * Load weekly imam schedule from display settings themeSettings JSON.
 */
export async function getWeeklyImamSettings(): Promise<WeeklyImamItem[]> {
  try {
    const display = await prisma.displaySetting.findFirst({
      orderBy: { id: "asc" },
      select: { themeSettings: true },
    });

    const theme = (display?.themeSettings as Record<string, unknown>) ?? null;
    if (theme && Array.isArray(theme.weeklyImam) && theme.weeklyImam.length > 0) {
      return theme.weeklyImam as WeeklyImamItem[];
    }

    return [];
  } catch (error) {
    console.error("Gagal membaca weekly imam settings:", error);
    return [];
  }
}

/**
 * Save weekly imam schedule to display settings themeSettings JSON,
 * and optionally sync rows to the database calendar.
 */
export async function saveWeeklyImamSettings(
  items: WeeklyImamItem[],
  syncDays = 14
): Promise<void> {
  await saveDisplayThemePatch({ weeklyImam: items });

  if (syncDays > 0) {
    await syncWeeklyToCalendar(items, syncDays);
  }
}

/**
 * Synchronize weekly schedule entries into `ImamMuadzinSchedule`
 * for the next N days. Rows previously generated by this sync are updated
 * (or removed when the rule no longer applies); manual overrides are kept.
 */
export async function syncWeeklyToCalendar(
  weeklyItems: WeeklyImamItem[],
  daysCount = 14
): Promise<number> {
  if (!weeklyItems) return 0;

  // Filter out items without an imamName
  const activeRules = weeklyItems.filter(
    (item) => item.isActive && item.imamName && item.imamName.trim() !== ""
  );

  const todayUTC = todayDateOnly();
  const endUTC = addDaysUTC(todayUTC, daysCount);

  // Fetch all existing entries in this window in one single query
  const existingEntries = await prisma.imamMuadzinSchedule.findMany({
    where: {
      scheduleDate: {
        gte: todayUTC,
        lt: endUTC,
      },
    },
    select: {
      id: true,
      scheduleDate: true,
      prayerName: true,
      imamName: true,
      muadzinName: true,
      notes: true,
      createdBy: true,
    },
  });

  const dateKey = (date: Date) => date.toISOString().slice(0, 10);
  const lookupKeyOf = (date: Date, prayerName: string) =>
    `${dateKey(date)}_${prayerName}`;

  const existingMap = new Map<
    string,
    (typeof existingEntries)[number]
  >();
  for (const entry of existingEntries) {
    existingMap.set(lookupKeyOf(entry.scheduleDate, entry.prayerName), entry);
  }

  const expectedKeys = new Set<string>();

  const entriesToCreate: Array<{
    scheduleDate: Date;
    prayerName: string;
    imamName: string;
    muadzinName: string;
    notes: string | null;
    createdBy: string;
  }> = [];

  const entriesToUpdate: Array<{
    id: string;
    imamName: string;
    muadzinName: string;
    notes: string | null;
  }> = [];

  for (let d = 0; d < daysCount; d++) {
    const targetDate = addDaysUTC(todayUTC, d);
    const dayOfWeek = targetDate.getUTCDay();
    const dateStr = dateKey(targetDate);

    const matchingRules = activeRules.filter((r) => r.dayOfWeek === dayOfWeek);

    for (const rule of matchingRules) {
      if (rule.effectiveFrom && dateStr < rule.effectiveFrom) continue;
      if (
        !rule.isPermanent &&
        rule.effectiveUntil &&
        dateStr > rule.effectiveUntil
      ) {
        continue;
      }

      const lookupKey = `${dateStr}_${rule.prayerName}`;
      expectedKeys.add(lookupKey);

      const nextImamName = rule.imamName.trim();
      const nextMuadzinName = rule.muadzinName ? rule.muadzinName.trim() : "";
      const nextNotes = rule.notes || null;

      const existing = existingMap.get(lookupKey);
      if (!existing) {
        entriesToCreate.push({
          scheduleDate: targetDate,
          prayerName: rule.prayerName,
          imamName: nextImamName,
          muadzinName: nextMuadzinName,
          notes: nextNotes,
          createdBy: "weekly-sync",
        });
        continue;
      }

      // Only touch rows generated by weekly sync; manual overrides stay intact.
      if (
        existing.createdBy === "weekly-sync" &&
        (existing.imamName !== nextImamName ||
          existing.muadzinName !== nextMuadzinName ||
          (existing.notes ?? null) !== nextNotes)
      ) {
        entriesToUpdate.push({
          id: existing.id,
          imamName: nextImamName,
          muadzinName: nextMuadzinName,
          notes: nextNotes,
        });
      }
    }
  }

  // Remove generated rows whose rule is no longer active/valid.
  const staleIds = existingEntries
    .filter(
      (entry) =>
        entry.createdBy === "weekly-sync" &&
        !expectedKeys.has(lookupKeyOf(entry.scheduleDate, entry.prayerName))
    )
    .map((entry) => entry.id);

  const BATCH_SIZE = 50;

  for (let i = 0; i < entriesToCreate.length; i += BATCH_SIZE) {
    const batch = entriesToCreate.slice(i, i + BATCH_SIZE);
    await prisma.imamMuadzinSchedule.createMany({
      data: batch,
      skipDuplicates: true,
    });
  }

  for (let i = 0; i < entriesToUpdate.length; i += BATCH_SIZE) {
    const batch = entriesToUpdate.slice(i, i + BATCH_SIZE);
    await prisma.$transaction(
      batch.map((entry) =>
        prisma.imamMuadzinSchedule.update({
          where: { id: entry.id },
          data: {
            imamName: entry.imamName,
            muadzinName: entry.muadzinName,
            notes: entry.notes,
          },
        })
      )
    );
  }

  if (staleIds.length > 0) {
    await prisma.imamMuadzinSchedule.deleteMany({
      where: { id: { in: staleIds } },
    });
  }

  return entriesToCreate.length + entriesToUpdate.length + staleIds.length;
}
